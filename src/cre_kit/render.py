def g(cfg, key):
    return C.get(cfg, key)


def base_ref(cfg) -> str:
    return f"{g(cfg, 'snowflake.registry_url')}{g(cfg, 'base_image.image_path')}"


def local_ref(cfg) -> str:
    return f"{g(cfg, 'image.name')}:{g(cfg, 'image.tag')}"


def repo_fqn(cfg) -> str:
    return f"{g(cfg, 'image_repo.database')}.{g(cfg, 'image_repo.schema')}.{g(cfg, 'image_repo.name')}"


def logical_image_path(cfg) -> str:
    """IMAGE_PATH for CREATE CUSTOM RUNTIME ENVIRONMENT: '/db/schema/repo/image:tag'."""
    path = "/".join(str(g(cfg, k)).lower() for k in ("image_repo.database", "image_repo.schema", "image_repo.name"))
    return f"/{path}/{local_ref(cfg)}"


def remote_ref(cfg) -> str:
    return f"{g(cfg, 'snowflake.registry_url')}{logical_image_path(cfg)}"


def package_name(spec: str) -> str:
    return re.split(r"[=<>!~\[ ;@]", spec.strip(), maxsplit=1)[0]


def dockerfile(cfg) -> str:
    lines = [
        "# Generated by cre-kit from cre.yaml. Do not hand-edit: change the config and re-render.",
        f"FROM {base_ref(cfg)}",
        "",
    ]
    args = [k for k in (g(cfg, "build.build_args") or {}) if k not in C.PREDEFINED_BUILD_ARGS]
    for name in args:
        lines.append(f"ARG {name}")
    if args:
        lines.append("")
    ca = g(cfg, "build.ca_bundle")
    if ca:
        lines += [f"COPY {CA_IN_CONTEXT} {CA_IN_IMAGE}", ""]
    pkgs = g(cfg, "build.pip_packages") or []
    if pkgs:
        prefix = f"SSL_CERT_FILE={CA_IN_IMAGE} " if ca else ""
        flags = ["--system", "--break-system-packages"]
        if g(cfg, "build.pip_index_url"):
            flags += ["--index-url", g(cfg, "build.pip_index_url")]
        for url in g(cfg, "build.pip_extra_index_urls") or []:
            flags += ["--extra-index-url", url]
        body = " \\\n    ".join([f"RUN {prefix}uv pip install {' '.join(flags)}"] + [f"'{p}'" for p in pkgs])
        lines += [body, ""]
    extra = g(cfg, "build.dockerfile_extra") or []
    if extra:
        lines += [str(e) for e in extra] + [""]
    return "\n".join(lines).rstrip() + "\n"


def create_cre_sql(cfg) -> str:
    replace = "OR REPLACE " if g(cfg, "cre.replace_existing") else ""
    return (
        f"CREATE {replace}CUSTOM RUNTIME ENVIRONMENT {g(cfg, 'cre.name')} "
        f"IMAGE_PATH = '{logical_image_path(cfg)}' "
        f"BASE_IMAGE_TYPE = {g(cfg, 'base_image.type')}"
    )


def describe_cre_sql(cfg) -> str:
    return f"DESCRIBE CUSTOM RUNTIME ENVIRONMENT {g(cfg, 'cre.name')}"


SHOW_CRES_SQL = "SHOW CUSTOM RUNTIME ENVIRONMENTS"


def show_repo_sql(cfg) -> str:
    return (f"SHOW IMAGE REPOSITORIES LIKE '{g(cfg, 'image_repo.name')}' "
            f"IN SCHEMA {g(cfg, 'image_repo.database')}.{g(cfg, 'image_repo.schema')}")


def create_repo_sql(cfg) -> str:
    return f"CREATE IMAGE REPOSITORY IF NOT EXISTS {repo_fqn(cfg)}"


def grants_sql(cfg) -> str:
    """Rendered for a human to review, never executed by the pipeline: the
    GRANT syntax for this object type is not shown on the custom runtime images
    doc page, so it is unverified."""
    roles = g(cfg, "cre.grant_usage_to") or []
    head = ("-- UNVERIFIED SYNTAX. The docs say a role needs USAGE on the CRE and access to the\n"
            "-- image repository, but do not show the GRANT statements. Review before running.\n")
    body = "".join(
        f"GRANT USAGE ON CUSTOM RUNTIME ENVIRONMENT {g(cfg, 'cre.name')} TO ROLE {r};\n"
        f"GRANT READ ON IMAGE REPOSITORY {repo_fqn(cfg)} TO ROLE {r};\n" for r in roles)
    return head + (body or "-- no roles listed in cre.grant_usage_to\n")


def usage_md(cfg) -> str:
    name = g(cfg, "cre.name")
    pool = g(cfg, "smoke_test.compute_pool") or "<COMPUTE_POOL>"
    stage = g(cfg, "smoke_test.stage_name") or "<payload_stage>"
    wh = g(cfg, "snowflake.warehouse") or "<WAREHOUSE>"
    return f"""# Using CRE `{name}`

Image: `{remote_ref(cfg)}`

## ML Jobs (snowflake-ml-python >= 1.37.0)

```python
from snowflake.ml import jobs

@jobs.remote("{pool}", stage_name="{stage}", runtime_environment="cre@{name}")
def train():
    ...

job = train()
```

## Notebooks (Preview)

In the Workspaces UI: advanced settings -> pick the registered custom image.

```sql
EXECUTE NOTEBOOK PROJECT <DB>.<SCHEMA>.<NOTEBOOK_PROJECT>
    MAIN_FILE = '<file>.ipynb'
    COMPUTE_POOL = '{pool}'
    RUNTIME = 'cre@{name}'
    QUERY_WAREHOUSE = '{wh}';
```

Code bundle specification: `runtime_version: 'cre@{name}'` under `compute_options`.

## Lifecycle

```sql
{describe_cre_sql(cfg)};
ALTER CUSTOM RUNTIME ENVIRONMENT {name} SET CRE_STATUS = DEPRECATED;  -- stops new jobs/notebooks
DROP CUSTOM RUNTIME ENVIRONMENT IF EXISTS {name};                      -- metadata only; image stays in the repo
```

Digest rule: the image digest is checked at run time. If the image behind this tag is
pushed again after registration, submissions are rejected until the CRE is recreated.
Use a new `image.tag` for every build.
"""


def smoke_job_py(cfg) -> str:
    pins = {package_name(p): p.split("==", 1)[1].strip() for p in (g(cfg, "build.pip_packages") or []) if "==" in p}
    role = g(cfg, "snowflake.role")
    return f'''"""Generated by cre-kit. Submits a tiny ML Job on the CRE and reports package versions."""
import json
import sys

from snowflake.ml import jobs
from snowflake.snowpark import Session

PACKAGES = {json.dumps(sorted(pins))}

session = Session.builder.config("connection_name", {g(cfg, "snowflake.connection")!r}).create()
{f"session.use_role({role!r})" if role else "# role: connection default"}


@jobs.remote({g(cfg, "smoke_test.compute_pool")!r}, stage_name={g(cfg, "smoke_test.stage_name")!r},
             runtime_environment="cre@{g(cfg, "cre.name")}", session=session)
def smoke():
    import importlib.metadata as md

    found = {{}}
    for name in PACKAGES:
        try:
            found[name] = md.version(name)
        except Exception:
            found[name] = "MISSING"
    return found


job = smoke()
status = job.wait()
print("CRE_SMOKE_STATUS", status)
if str(status).upper() != "DONE":
    print(job.get_logs())
    sys.exit(1)
print("CRE_SMOKE_RESULT", json.dumps(job.result()))
'''


